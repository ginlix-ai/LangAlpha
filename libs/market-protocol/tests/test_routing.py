class TestOrderProviders:
    def test_not_entitled_is_excluded(self):
        out = order_providers(Surface.DAILY, [_probe("a", entitled=False), _probe("b")])
        assert [p.name for p in out] == ["b", "a"]
        assert out[1].excluded_reason == "not_entitled"

    def test_no_coverage_is_excluded(self):
        out = order_providers(Surface.DAILY, [_probe("a", coverage_hit=0), _probe("b")])
        assert {p.name: p.excluded_reason for p in out} == {"a": "no_coverage", "b": None}

    def test_incomplete_session_excluded_for_bars_only(self):
        bars = order_providers(Surface.INTRADAY, [_probe("a", session_complete=False)])
        assert bars[0].excluded_reason == "incomplete_session"
        snaps = order_providers(Surface.SNAPSHOT, [_probe("a", session_complete=False)])
        assert snaps[0].excluded_reason is None

    def test_bad_anchors_excluded(self):
        out = order_providers(Surface.INTRADAY, [_probe("a", anchors_ok=False)])
        assert out[0].excluded_reason == "bad_anchors"

    def test_quota_below_floor_excluded_for_bars_only(self):
        bars = order_providers(Surface.INTRADAY, [_probe("a", calls_per_minute=1)])
        assert bars[0].excluded_reason == "quota_below_floor"
        snaps = order_providers(Surface.SNAPSHOT, [_probe("a", calls_per_minute=1)])
        assert snaps[0].excluded_reason is None

    def test_measured_lag_outranks_declared_tier(self):
        out = order_providers(
            Surface.INTRADAY,
            [_probe("slow", lag_s=600, tier="realtime"), _probe("fast", lag_s=10, tier="delayed_15m")],
        )
        assert [p.name for p in out] == ["fast", "slow"]

    def test_ties_keep_probe_order(self):
        out = order_providers(Surface.DAILY, [_probe("a", tier="eod"), _probe("b", tier="eod")])
        assert [p.name for p in out] == ["a", "b"]

    def test_excluded_always_rank_last(self):
        out = order_providers(
            Surface.DAILY, [_probe("dead", entitled=False, lag_s=0), _probe("live", lag_s=300)]
        )
        assert [p.name for p in out] == ["live", "dead"]

    def test_input_is_not_mutated(self):
        original = _probe("a", entitled=False)
        order_providers(Surface.DAILY, [original])
        assert original.excluded_reason is None

    def test_a_feed_measured_past_the_delayed_ceiling_ranks_below_a_delayed_one(self):
        # Declared realtime but measured at 20 minutes: ranked by what it did,
        # which is end-of-day freshness, not by what it claims.
        out = order_providers(
            Surface.INTRADAY,
            [_probe("stale", lag_s=1200, tier="realtime"), _probe("delayed", lag_s=120, tier="delayed_15m")],
        )
        assert [p.name for p in out] == ["delayed", "stale"]

    @pytest.mark.parametrize("declared", [None, "delayed_15m"])
    def test_a_measured_live_feed_outranks_an_unmeasured_realtime_claim(self, declared):
        out = order_providers(
            Surface.INTRADAY,
            [_probe("claimed", tier="realtime"), _probe("measured", lag_s=10, tier=declared)],
        )
        assert [p.name for p in out] == ["measured", "claimed"]

    def test_quota_outranks_cost(self):
        out = order_providers(
            Surface.INTRADAY,
            [_probe("cheap", calls_per_minute=50, cost_calls=1),
             _probe("roomy", calls_per_minute=500, cost_calls=4)],
        )
        assert [p.name for p in out] == ["roomy", "cheap"]

    def test_equal_lag_prefers_more_calls_per_minute(self):
        out = order_providers(
            Surface.INTRADAY,
            [_probe("tight", lag_s=30, calls_per_minute=50), _probe("roomy", lag_s=30, calls_per_minute=500)],
        )
        assert [p.name for p in out] == ["roomy", "tight"]

    # Each default below is pinned by pairing an unset provider with a set one,
    # so moving the default either way reorders the pair.

    def test_an_undeclared_treatment_ranks_with_raw_on_daily(self):
        out = order_providers(
            Surface.DAILY,
            [_probe("raw", lag_s=300, price_treatment="raw"),
             _probe("undeclared", lag_s=10),
             _probe("adjusted", lag_s=600, price_treatment="dividend_adjusted")],
        )
        assert [p.name for p in out] == ["adjusted", "undeclared", "raw"]

    def test_neither_lag_nor_tier_ranks_below_an_eod_claim(self):
        out = order_providers(Surface.INTRADAY, [_probe("unknown"), _probe("eod", tier="eod")])
        assert [p.name for p in out] == ["eod", "unknown"]

    def test_an_unstated_quota_ranks_as_unlimited(self):
        out = order_providers(
            Surface.INTRADAY, [_probe("stated", calls_per_minute=100_000), _probe("unstated")]
        )
        assert [p.name for p in out] == ["unstated", "stated"]

    def test_a_quota_at_the_floor_stays_routable(self):
        (at_floor,) = order_providers(
            Surface.INTRADAY, [_probe("a", calls_per_minute=MIN_CALLS_PER_MINUTE_FOR_BARS)]
        )
        assert at_floor.routable
        (below,) = order_providers(
            Surface.INTRADAY, [_probe("a", calls_per_minute=MIN_CALLS_PER_MINUTE_FOR_BARS - 1)]
        )
        assert below.excluded_reason == "quota_below_floor"

    def test_a_feed_stamped_hours_ahead_ranks_with_no_lag_and_no_tier(self):
        # Local time read as UTC: eight hours "ahead", recorded with the realtime
        # class that lag earns, so neither may outrank an honest feed.
        out = order_providers(
            Surface.INTRADAY,
            [_probe("ahead", lag_s=-28800, tier="realtime"),
             _probe("eod", tier="eod"),
             _probe("delayed", lag_s=600, tier="delayed_15m")],
        )
        assert [p.name for p in out] == ["delayed", "eod", "ahead"]

    @pytest.mark.parametrize("lag_s,first", [(-60, "skewed"), (-61, "honest")])
    def test_seconds_of_clock_skew_still_count_as_a_measurement(self, lag_s, first):
        out = order_providers(
            Surface.INTRADAY,
            [_probe("honest", lag_s=30, tier="realtime"), _probe("skewed", lag_s=lag_s, tier="realtime")],
        )
        assert out[0].name == first

    def test_daily_ranks_adjusted_series_above_raw(self):
        raw = _probe("fmp", session_complete=True, tier="delayed_15m", price_treatment="raw", cost_calls=1)
        qfq = _probe("tushare", session_complete=True, tier="eod", price_treatment="dividend_adjusted",
                     cost_calls=4)
        assert [p.name for p in order_providers(Surface.DAILY, [raw, qfq])] == ["tushare", "fmp"]
        # Intraday does not weigh adjustment: the cheaper, fresher raw feed wins.
        assert [p.name for p in order_providers(Surface.INTRADAY, [raw, qfq])] == ["fmp", "tushare"]

    def test_surface_value_applies_the_same_policy(self):
        raw = _probe("fmp", lag_s=10, tier="realtime", price_treatment="raw")
        qfq = _probe("tushare", tier="eod", price_treatment="split_adjusted")
        assert [p.name for p in order_providers("daily", [raw, qfq])] == ["tushare", "fmp"]
        assert order_providers("snapshot", [_probe("a", calls_per_minute=1)])[0].excluded_reason is None
        with pytest.raises(ValueError):
            order_providers("nonsense", [raw])

    def test_daily_adjustment_outranks_a_fresher_measured_feed(self):
        raw = _probe("fmp", lag_s=10, tier="realtime", price_treatment="raw", calls_per_minute=300)
        qfq = _probe("tushare", tier="eod", price_treatment="split_adjusted", calls_per_minute=50)
        assert [p.name for p in order_providers(Surface.DAILY, [raw, qfq])] == ["tushare", "fmp"]

    def test_throttled_to_zero_rows_reads_quota_not_coverage(self):
        throttled = _probe("tushare", coverage_hit=0, coverage_total=3, calls_per_minute=1)
        (p,) = order_providers(Surface.INTRADAY, [throttled])
        assert p.excluded_reason == "quota_below_floor"


