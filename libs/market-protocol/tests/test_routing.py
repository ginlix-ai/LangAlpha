def _write_ruleset(ruleset: Ruleset, path: Path) -> Path:
    """Write *ruleset* as a probe would; where and how it lands is the deployment's concern."""
    path.write_text(yaml.safe_dump(ruleset.model_dump(mode="json"), sort_keys=False))
    return path


