class TestLoadRuleset:
    def test_save_load_roundtrip(self, tmp_path):
        rs = Ruleset(
            generated_at=NOW,
            providers={"fmp": ProviderInfo(fingerprint="abcd1234")},
            cells=[_cell(INTRADAY_1M, [_probe("fmp", lag_s=12, tier="realtime")])],
        )
        path = _write_ruleset(rs, tmp_path / "data_routing.yaml")
        loaded = load_ruleset(path)
        assert loaded is not None
        assert loaded.providers["fmp"].fingerprint == "abcd1234"
        assert loaded.cells[0].key == INTRADAY_1M
        assert loaded.cells[0].providers[0].lag_s == 12

    def test_missing_file_is_none(self, tmp_path):
        assert load_ruleset(tmp_path / "nope.yaml") is None

    def test_unreadable_file_is_none(self, tmp_path):
        path = tmp_path / "data_routing.yaml"
        path.write_text("cells: [ this is not a ruleset\n")
        assert load_ruleset(path) is None

    def test_wrong_shape_is_none(self, tmp_path):
        path = tmp_path / "data_routing.yaml"
        path.write_text(f"version: {RULESET_VERSION}\ngenerated_at: '2026-09-09T12:00:00Z'\ncells: 7\n")
        assert load_ruleset(path) is None

    def test_version_mismatch_is_none(self, tmp_path):
        rs = Ruleset(generated_at=NOW, cells=[_cell(INTRADAY_1M, [_probe("fmp")])])
        path = _write_ruleset(rs, tmp_path / "data_routing.yaml")
        path.write_text(path.read_text().replace(f"version: {RULESET_VERSION}", "version: 99", 1))
        assert load_ruleset(path) is None

    def test_interval_is_stored_as_the_schema_id(self):
        assert INTRADAY_1M.interval == "ohlcv-1m"
        assert CellKey(market="cn", asset_class="equity", surface=Surface.INTRADAY,
                       interval="1min") == INTRADAY_1M

    def test_version_1_file_migrates_its_bare_intervals(self, tmp_path):
        path = tmp_path / "data_routing.yaml"
        path.write_text(
            "version: 1\n"
            "generated_at: '2026-09-09T12:00:00Z'\n"
            "cells:\n"
            "- key: {market: cn, asset_class: equity, surface: intraday, interval: 5m}\n"
            "  probed_at: '2026-09-09T12:00:00Z'\n"
            "  providers:\n"
            "  - {name: fmp, coverage_hit: 2, coverage_total: 2}\n"
        )
        loaded = load_ruleset(path)
        assert loaded is not None and loaded.version == RULESET_VERSION
        assert loaded.cells[0].key.interval == "ohlcv-5m"
        assert RoutingTable(loaded).order_for("intraday", "cn", "equity", "5min") == ["fmp"]

    def test_a_hand_written_version_2_file_routes_in_its_written_order(self, tmp_path):
        path = tmp_path / "data_routing.yaml"
        path.write_text(V2_RULESET)
        loaded = load_ruleset(path)
        assert loaded is not None and loaded.version == 2
        assert loaded.providers["fmp"].fingerprint == "abcd1234"
        assert [c.phase_at_probe for c in loaded.cells] == ["open", "closed", "open"]
        assert loaded.cells[0].providers[1].notes == ["https://example.com/bars?from=1&limit=5000"]
        table = RoutingTable(loaded)
        assert table.order_for("intraday", "cn", "equity", "1m") == ["tushare", "fmp"]
        assert table.order_for("daily", "cn", "equity") == ["tushare", "fmp"]
        # The policy would put tushare first here; the file's order is what routes.
        snapshot = loaded.cells[2]
        assert [p.name for p in order_providers(snapshot.key.surface, snapshot.providers)] == [
            "tushare", "fmp",
        ]
        assert table.order_for("snapshot", "cn", "equity") == ["fmp", "tushare"]

    def test_a_str_path_loads(self, tmp_path):
        path = tmp_path / "data_routing.yaml"
        path.write_text(V2_RULESET)
        loaded = load_ruleset(str(path))
        assert loaded is not None and len(loaded.cells) == 3

    def test_a_directory_is_none(self, tmp_path, caplog):
        with caplog.at_level("WARNING", logger=LOGGER):
            assert load_ruleset(tmp_path) is None
        assert "data_routing.ruleset.unreadable" in caplog.text

    def test_a_missing_version_is_none(self, tmp_path, caplog):
        path = tmp_path / "data_routing.yaml"
        path.write_text("generated_at: '2026-09-09T12:00:00Z'\ncells: []\n")
        with caplog.at_level("WARNING", logger=LOGGER):
            assert load_ruleset(path) is None
        assert "data_routing.ruleset.unreadable" in caplog.text and "version" in caplog.text

    def test_an_unknown_version_is_a_mismatch_even_when_its_cells_do_not_validate(
        self, tmp_path, caplog
    ):
        path = tmp_path / "data_routing.yaml"
        path.write_text(
            "version: 3\n"
            "generated_at: '2026-09-09T12:00:00Z'\n"
            "cells:\n"
            "- key: {market: cn, asset_class: option, surface: greeks}\n"
        )
        with caplog.at_level("INFO", logger=LOGGER):
            assert load_ruleset(path) is None
        (record,) = caplog.records
        assert record.getMessage().startswith("data_routing.ruleset.version_mismatch")
        assert "file=3" in record.getMessage()

    def test_anchors_and_aliases_are_refused(self, tmp_path, caplog):
        path = tmp_path / "data_routing.yaml"
        path.write_text(
            f"version: {RULESET_VERSION}\n"
            "generated_at: '2026-09-09T12:00:00Z'\n"
            "cells:\n"
            "- &cell\n"
            "  key: {market: cn, asset_class: equity, surface: daily}\n"
            "  probed_at: '2026-09-09T12:00:00Z'\n"
            "- *cell\n"
        )
        with caplog.at_level("WARNING", logger=LOGGER):
            assert load_ruleset(path) is None
        assert "anchors and aliases" in caplog.text

    def test_a_malformed_cell_is_skipped_and_the_rest_load(self, tmp_path, caplog):
        path = tmp_path / "data_routing.yaml"
        path.write_text(
            f"version: {RULESET_VERSION}\n"
            "generated_at: '2026-09-09T12:00:00Z'\n"
            "cells:\n"
            "- key: {market: cn, asset_class: equity, surface: daily}\n"
            "  probed_at: '2026-09-09T12:00:00Z'\n"
            "  providers: [{name: tushare, coverage_hit: 1, coverage_total: 1}]\n"
            "- key: {market: us, asset_class: equity, surface: daily}\n"
            "  probed_at: yesterday\n"
            "- key: {market: hk, asset_class: equity, surface: snapshot}\n"
            "  probed_at: '2026-09-09T12:00:00Z'\n"
            "  providers: [{name: fmp, coverage_hit: 1, coverage_total: 1}]\n"
        )
        with caplog.at_level("WARNING", logger=LOGGER):
            loaded = load_ruleset(path)
        assert loaded is not None
        assert [c.key.as_str() for c in loaded.cells] == ["cn/equity/daily", "hk/equity/snapshot"]
        (record,) = caplog.records
        assert "data_routing.ruleset.cell_skipped" in record.getMessage()
        assert "key=us/equity/daily" in record.getMessage()
        table = RoutingTable(loaded)
        assert table.order_for("daily", "us", "equity") is None
        assert table.order_for("snapshot", "hk", "equity") == ["fmp"]

        # A writer merging into the file must not drop the cell it could not read.
        with pytest.raises(ValueError, match="us/equity/daily"):
            load_ruleset(path, strict=True)

    @pytest.mark.parametrize(
        "text",
        ["cells: [ this is not a ruleset\n", "version: 99\ngenerated_at: '2026-09-09T12:00:00Z'\n"],
        ids=["unreadable", "unknown-version"],
    )
    def test_strict_raises_for_a_file_a_writer_would_overwrite(self, tmp_path, text):
        # None would read as "no file yet", and the rewrite would start over.
        path = tmp_path / "data_routing.yaml"
        path.write_text(text)
        with pytest.raises(ValueError):
            load_ruleset(path, strict=True)

    def test_strict_is_none_only_when_absent(self, tmp_path):
        assert load_ruleset(tmp_path / "nope.yaml", strict=True) is None


@pytest.mark.parametrize(
    "surface,interval",
    [(Surface.INTRADAY, "ohlcv-1m"), (Surface.DAILY, None), (Surface.SNAPSHOT, None)],
)
def test_cell_key_as_str(surface, interval):
    key = CellKey(market="cn", asset_class="fund", surface=surface, interval=interval)
    tail = f"/{interval}" if interval else ""
    assert key.as_str() == f"cn/fund/{surface.value}{tail}"

