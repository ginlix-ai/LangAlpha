// The web app names a Bash step that runs `la` for what it did, which means
// reading the command under this CLI's grammar. web/ builds on its own and
// cannot import this package, so it reads a generated module written here: the
// grammar's own source, verbatim, and the command table it reads against.
// test/webGrammar.test.ts regenerates it and fails on any difference.
import { readFileSync } from "node:fs";
import type { Flags } from "../src/args.js";
import { GLOBAL } from "../src/commands/command.js";
import { COMMANDS } from "../src/commands/index.js";

/** Where the module lives, and the grammar it carries, from this package's directory. */
export const WEB_GRAMMAR = "../web/src/pages/ChatAgent/utils/laGrammar.generated.ts";
const GRAMMAR_SOURCE = "src/grammar.ts";

const HEADER = `// Generated by cli/scripts/web-grammar.ts from the CLI's grammar and command table.
// Do not edit: run \`pnpm gen:web-grammar\` in cli/ instead. cli/test/webGrammar.test.ts
// regenerates and diffs this file, so an edit here fails CI rather than drifting.
`;

/** What parsing needs of a flag: its help and placeholder stay behind. */
function parseOnly(flags: Flags = {}): Record<string, { type: string; short?: string; required?: true }> {
  return Object.fromEntries(
    Object.entries(flags).map(([name, f]) => [
      name,
      { type: f.type, ...(f.short ? { short: f.short } : {}), ...(f.required ? { required: true as const } : {}) },
    ]),
  );
}

export function webGrammar(): string {
  const grammar = readFileSync(GRAMMAR_SOURCE, "utf8");
  // Copied as it stands, so it can name nothing outside itself.
  if (/^\s*(import|export .* from)\b/m.test(grammar)) throw new Error(`${GRAMMAR_SOURCE} must not import`);
  const commands = COMMANDS.map(
    (c) => `  ${JSON.stringify({ words: c.words, operands: c.operands ?? [], flags: parseOnly(c.flags) })},`,
  );
  return `${HEADER}
// cli/src/grammar.ts

${grammar}
// The command table, from cli/src/commands.

/** The options every command takes, which may also come before its words. */
export const LA_GLOBAL_FLAGS: FlagSpecs = ${JSON.stringify(parseOnly(GLOBAL), null, 2)};

export const LA_COMMANDS: readonly CommandSpec[] = [
${commands.join("\n")}
];
`;
}
