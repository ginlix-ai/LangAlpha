// Writes the bridge part the app's viewers share with a framed page: how a
// quote is found again and where a pin goes, compiled from the TypeScript the
// app runs (SOURCES) into `comments-shared.generated.js`, with the global
// declarations the other parts are type-checked against beside it.
//
//   cd web && node ../src/server/preview_proxy/bridge/generate-shared.mjs          # write
//   cd web && node ../src/server/preview_proxy/bridge/generate-shared.mjs --check  # fail if stale
//
// Runs on web's toolchain (its `typescript`, the TS 6 API) from outside web,
// as `make test-bridge` does, so web itself never reads this folder.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '../../../..');
const WEB = join(REPO, 'web');
const SOURCES = [
  'web/src/pages/ChatAgent/components/viewers/comments/pageText.ts',
  'web/src/pages/ChatAgent/components/viewers/comments/pinRoom.ts',
];
const PART = 'comments-shared.generated';
const JS = join(HERE, `${PART}.js`);
const DTS = join(HERE, `${PART}.d.ts`);

const ts = createRequire(join(WEB, 'package.json'))('typescript');

function fail(message) {
  console.error(`generate-shared: ${message}`);
  process.exit(1);
}

/** TypeScript's four-space indent as the hand-written parts' two. */
const reindent = (text) => text.replace(/^( {4})+/gm, (lead) => ' '.repeat(lead.length / 2));

function compile(path) {
  const source = readFileSync(join(REPO, path), 'utf8');
  // ES5, the level every hand-written part keeps: they are spliced into
  // pages of any age, and one syntax error there takes the whole bridge.
  const js = ts.transpileModule(source, {
    fileName: path,
    reportDiagnostics: true,
    compilerOptions: { target: ts.ScriptTarget.ES5, module: ts.ModuleKind.ESNext, ignoreDeprecations: '6.0', newLine: ts.NewLineKind.LineFeed },
  });
  const dts = ts.transpileDeclaration(source, {
    fileName: path,
    reportDiagnostics: true,
    compilerOptions: { newLine: ts.NewLineKind.LineFeed },
  });
  const problems = [...(js.diagnostics ?? []), ...(dts.diagnostics ?? [])];
  if (problems.length) fail(`${path}: ${problems.map((d) => ts.flattenDiagnosticMessageText(d.messageText, ' ')).join('; ')}`);
  // One scope with the other parts: each export becomes a plain declaration
  // there, and anything that would hide or import a name cannot stand.
  const body = js.outputText.replace(/^export (?=function |var )/gm, '');
  const declared = dts.outputText.replace(/^export declare /gm, 'declare ').replace(/^export (?=interface |type )/gm, '');
  for (const [kind, text] of [['script', body], ['declarations', declared]]) {
    const left = /^\s*(import|export)\b.*$/m.exec(text);
    if (left) fail(`${path}: its ${kind} keep a module statement the bridge's one scope cannot: ${left[0]}`);
  }
  // A helper TypeScript would inject (__spreadArray, __assign, ...) means the
  // source used syntax ES5 lacks; it belongs rewritten, not shipped.
  const helper = /\b__[a-zA-Z]+\(/.exec(body);
  if (helper) fail(`${path}: compiles to the helper ${helper[0]}; write it in syntax ES5 has`);
  return { body: reindent(body).trim(), declared: reindent(declared).trim() };
}

const topNames = (text) => new Set([...text.matchAll(/^(?:function|var|let|const) ([A-Za-z_$][\w$]*)/gm)].map((m) => m[1]));

function generate() {
  const parts = SOURCES.map(compile);
  const named = SOURCES.join(' and ');
  const header = (what) =>
    `// GENERATED by src/server/preview_proxy/bridge/generate-shared.mjs from ${named}: do not edit.\n` +
    `// ${what} Change the sources and run \`make bridge-shared\`.\n`;
  const js = `${header('The bridge part the app and a framed page share.')}\n${parts.map((p) => p.body).join('\n\n')}\n`;
  const dts = `${header('What the part declares in the bridge\'s one scope.')}\n${parts.map((p) => p.declared).join('\n\n')}\n`;
  // Spliced as bytes into documents of any ASCII-compatible encoding, where
  // a closing script tag would end the bridge early (`page_bridge._part`).
  const wide = /[^\x00-\x7f]/.exec(js);
  if (wide) fail(`the part must be ASCII; write ${JSON.stringify(wide[0])} as an escape in the source`);
  if (/<\/script/i.test(js)) fail('the part must not hold a closing script tag');
  const own = topNames(js);
  for (const file of readdirSync(HERE)) {
    if (!file.endsWith('.js') || file === `${PART}.js`) continue;
    for (const name of topNames(readFileSync(join(HERE, file), 'utf8'))) {
      if (own.has(name)) fail(`${name} is declared both here and in ${file}, which share one scope`);
    }
  }
  return { js, dts };
}

const { js, dts } = generate();
if (process.argv.includes('--check')) {
  const stale = [[JS, js], [DTS, dts]].filter(([path, text]) => {
    try {
      return readFileSync(path, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    fail(`${stale.map(([path]) => relative(REPO, path)).join(', ')} out of date with ${SOURCES.join(', ')}; run \`make bridge-shared\``);
  }
} else {
  writeFileSync(JS, js);
  writeFileSync(DTS, dts);
}
